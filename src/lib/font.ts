function toBoolRows(rows: string[]): boolean[][] {
  return rows.map((row) => {
    const cells: boolean[] = []
    for (let x = 0; x < GLYPH_WIDTH; x++) {
      cells.push(row[x] === '#')
    }
    return cells
  })
}

export function getGlyph(char: string): boolean[][] {
  const accent = ACCENTED[char]
  if (accent) {
    const body = BODY[accent.base] ?? BLANK_BODY
    const mark = MARKS[accent.mark] ?? BLANK_MARK
    return toBoolRows([...mark.slice(0, MARK_HEIGHT), ...body.slice(0, BODY_HEIGHT)])
  }
  const body = BODY[char] ?? BLANK_BODY
  return toBoolRows([...BLANK_MARK, ...body.slice(0, BODY_HEIGHT)])
}
